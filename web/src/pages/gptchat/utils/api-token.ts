/**
 * API token helpers shared by the GPTChat config layer.
 *
 * The API token and the sync key are both secrets that live side by side in
 * the settings sidebar. Browser password managers have been observed copying
 * the sync key into the API key field, so this module also owns the invariant
 * that an API token must never be a misplaced sync key: the sync key alone
 * unlocks the user's synced history, so it must never travel to an API
 * provider as a bearer token.
 *
 * Every helper here classifies token *shape* only. None of them proves that
 * a token is valid; only the API endpoint can do that.
 */
import { constantTimeEqual } from '@/utils/constant-time'
import { secureRandomString } from '@/utils/secure-random'
import { DefaultSessionConfig, type SessionConfig } from '../types'

/**
 * ApiTokenKind classifies a token by shape without exposing its secret material.
 */
export type ApiTokenKind =
  'missing' | 'legacy-default' | 'freetier' | 'byok' | 'custom'

/**
 * FREETIER_TOKEN_PREFIX prefixes every anonymous free-tier token; the backend
 * routes requests by this prefix.
 */
export const FREETIER_TOKEN_PREFIX = 'FREETIER-'

/**
 * RANDOM_SECRET_LENGTH is the number of random base-36 characters in a newly
 * generated sync key or free-tier token (about 165 bits of entropy).
 */
const RANDOM_SECRET_LENGTH = 32

/**
 * createFreeTierToken builds a random free-tier token for anonymous sessions
 * from a CSPRNG. It returns a new `FREETIER-` prefixed token string.
 */
export function createFreeTierToken(): string {
  return FREETIER_TOKEN_PREFIX + secureRandomString(RANDOM_SECRET_LENGTH)
}

/**
 * describeApiTokenKind summarizes the token shape without exposing secret material.
 * It accepts any possibly-empty token and returns its ApiTokenKind.
 */
export function describeApiTokenKind(token?: string | null): ApiTokenKind {
  const trimmed = token?.trim() || ''
  if (!trimmed) return 'missing'
  if (trimmed === 'DEFAULT_PROXY_TOKEN') return 'legacy-default'
  if (trimmed.startsWith(FREETIER_TOKEN_PREFIX)) return 'freetier'
  if (trimmed.startsWith('sk-') || trimmed.startsWith('laisky-')) {
    return 'byok'
  }
  return 'custom'
}

/**
 * SYNC_KEY_PREFIX prefixes every auto-generated sync key.
 */
export const SYNC_KEY_PREFIX = 'sync-'

/**
 * GENERATED_SYNC_KEY_PATTERN matches every sync key GPTChat has ever
 * generated: the SPA's base-36 keys and the legacy page's 64-character
 * alphanumeric keys. Values that merely start with `sync-` (for example a
 * provider token containing `/`, `_`, or `.`) do not match.
 */
const GENERATED_SYNC_KEY_PATTERN = /^sync-[A-Za-z0-9]{12,}$/

/**
 * isGeneratedSyncKey reports whether value has the exact shape of a sync key
 * generated by GPTChat. It returns true for such keys, including older ones
 * that are no longer the active sync key.
 */
export function isGeneratedSyncKey(value?: string | null): boolean {
  return GENERATED_SYNC_KEY_PATTERN.test(value?.trim() || '')
}

/**
 * createSyncKey builds a random sync key for a browser that has none yet from
 * a CSPRNG. The backend derives the storage location and the encryption key
 * of the user's synced data from it, so it must be unguessable.
 * It returns a new `sync-` prefixed key string.
 */
export function createSyncKey(): string {
  return SYNC_KEY_PREFIX + secureRandomString(RANDOM_SECRET_LENGTH)
}

/**
 * apiTokenCollidesWithSyncKey reports whether apiToken is a `custom`-kind
 * token identical to syncKey. A recognizable API token (`sk-`, `laisky-`,
 * `FREETIER-`) never collides: its issuer already knows it, so reusing it as
 * the sync key leaks nothing. The comparison runs in constant time.
 * It returns true when the pair must not be stored together.
 */
export function apiTokenCollidesWithSyncKey(
  apiToken?: string | null,
  syncKey?: string | null,
): boolean {
  const token = apiToken?.trim() || ''
  const key = syncKey?.trim() || ''
  if (!token || !key || describeApiTokenKind(token) !== 'custom') {
    return false
  }
  return constantTimeEqual(token, key)
}

/**
 * isApiTokenClobberedBySyncKey reports whether apiToken is really a sync key
 * that ended up in the API key slot (the password-manager autofill bug).
 *
 * A token qualifies when it has the exact shape of a generated sync key,
 * which also catches copies of an older sync key, or when it collides with
 * the current syncKey (see apiTokenCollidesWithSyncKey).
 * It returns true when the token must be treated as corrupted.
 */
export function isApiTokenClobberedBySyncKey(
  apiToken?: string | null,
  syncKey?: string | null,
): boolean {
  if (isGeneratedSyncKey(apiToken)) {
    return true
  }
  return apiTokenCollidesWithSyncKey(apiToken, syncKey)
}

/**
 * isUserSuppliedApiToken reports whether apiToken has the shape of a
 * credential the user entered: a `byok` or `custom` token that is not a
 * clobbered sync key. Free-tier, legacy-default, and missing tokens do not
 * count. It checks shape only and says nothing about validity.
 * It returns true when the token can stand in for the user's own API key.
 */
export function isUserSuppliedApiToken(
  apiToken?: string | null,
  syncKey?: string | null,
): boolean {
  const kind = describeApiTokenKind(apiToken)
  if (kind !== 'byok' && kind !== 'custom') {
    return false
  }

  return !isApiTokenClobberedBySyncKey(apiToken, syncKey)
}

/**
 * normalizeApiBase canonicalizes an API base URL so endpoint identity can be
 * compared: an empty value means the default endpoint, scheme and host are
 * lower-cased, default ports and trailing slashes are dropped.
 * It returns the canonical form, or the trimmed input when it is not a URL.
 */
export function normalizeApiBase(apiBase?: string | null): string {
  const raw = apiBase?.trim() || DefaultSessionConfig.api_base
  try {
    const url = new URL(raw)
    const path = url.pathname.replace(/\/+$/, '')
    return `${url.protocol}//${url.host}${path}${url.search}`
  } catch {
    return raw.replace(/\/+$/, '')
  }
}

/**
 * isSameApiEndpoint reports whether the API bases a and b address the same
 * endpoint after normalization. Credentials may only move between configs
 * that share an endpoint, because the token is sent to that endpoint.
 * It returns true when both bases normalize to the same URL.
 */
export function isSameApiEndpoint(
  a?: string | null,
  b?: string | null,
): boolean {
  return normalizeApiBase(a) === normalizeApiBase(b)
}

/**
 * ApiTokenRecovery is the outcome of findRecoverableApiToken. token is the
 * recovered credential (empty unless outcome is 'recovered'); outcome is
 * 'recovered' for exactly one candidate, 'none' for no candidate, and
 * 'ambiguous' when distinct candidates disagree; candidates counts the
 * distinct candidate tokens.
 */
export interface ApiTokenRecovery {
  token: string
  outcome: 'recovered' | 'none' | 'ambiguous'
  candidates: number
}

/**
 * findRecoverableApiToken looks for the credential a clobbered session lost.
 * configs are the other sessions; target.apiBase is the endpoint the
 * recovered token will be sent to and target.syncKey the active sync key.
 *
 * Only user-supplied tokens of sessions on the same endpoint qualify, and a
 * token is recovered only when every qualifying session agrees on it:
 * distinct candidates mean distinct accounts, and guessing could bill or
 * expose the wrong one, so that case is left to the user.
 * It returns the recovery outcome.
 */
export function findRecoverableApiToken(
  configs: ReadonlyArray<Partial<SessionConfig> | null | undefined>,
  target: { apiBase?: string | null; syncKey?: string | null },
): ApiTokenRecovery {
  const candidates: string[] = []
  for (const config of configs) {
    const token = config?.api_token?.trim() || ''
    if (!isUserSuppliedApiToken(token, target.syncKey)) continue
    if (!isSameApiEndpoint(config?.api_base, target.apiBase)) continue
    if (candidates.some((known) => constantTimeEqual(known, token))) continue
    candidates.push(token)
  }

  if (candidates.length === 1) {
    return { token: candidates[0], outcome: 'recovered', candidates: 1 }
  }
  return {
    token: '',
    outcome: candidates.length === 0 ? 'none' : 'ambiguous',
    candidates: candidates.length,
  }
}

/**
 * canCompleteApiTokenReset reports whether a pending API key reset on config
 * may be marked done: a reset is pending and the session now holds a key of
 * the user's own. Callers invoke it on a completion action (leaving the API
 * key field or closing the settings), never per keystroke, so a half-typed
 * key does not silence the alert.
 * It returns true when api_token_reset_required should be cleared.
 */
export function canCompleteApiTokenReset(
  config: Pick<
    SessionConfig,
    'api_token' | 'api_token_reset_required' | 'sync_key'
  >,
): boolean {
  return (
    config.api_token_reset_required === true &&
    isUserSuppliedApiToken(config.api_token, config.sync_key)
  )
}
